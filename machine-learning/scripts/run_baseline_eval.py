#!/usr/bin/env python3
"""Generate the synthetic UI/text corpus (if missing) and evaluate the
baseline pretrained classifier (Falconsai/nsfw_image_detection by default)
against it, printing a score-distribution + threshold-sweep report.

Also evaluates any additional benign corpora listed in `EXTRA_BENIGN_CORPORA`
that happen to exist under `--eval-dir` (e.g. `real-world-macbook`, a small
manually captured screenshot batch — see the README). These are never
generated by this script and are skipped with a note when absent, since
unlike the synthetic corpus they cannot be reproduced from code.

Usage:
    .venv/bin/python scripts/run_baseline_eval.py [--count 300] [--seed 0]
        [--eval-dir data/eval] [--model Falconsai/nsfw_image_detection]

Corpus data lands under the gitignored `data/` directory and is never
committed.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

from holy_blocker_ml import eval as eval_mod
from holy_blocker_ml import model as model_mod
from holy_blocker_ml import synth_ui
from holy_blocker_ml.corpus import CorpusKind, CorpusSpec, discover_corpora

# Corpora this script knows how to look for but does not generate. Add a name
# here once a new manually-placed corpus directory convention exists; the
# script picks it up automatically on the next run without further changes.
EXTRA_BENIGN_CORPORA: tuple[str, ...] = ("real-world-macbook",)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--count", type=int, default=300)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument(
        "--eval-dir",
        type=Path,
        default=Path(__file__).resolve().parent.parent / "data" / "eval",
    )
    parser.add_argument("--model", default=model_mod.DEFAULT_MODEL_ID)
    args = parser.parse_args()

    synthetic_dir = args.eval_dir / "synthetic-ui"
    if synth_ui.corpus_matches(synthetic_dir, args.count, args.seed):
        print(f"reusing existing corpus in {synthetic_dir} (count={args.count}, seed={args.seed})")
    else:
        print(f"generating {args.count} synthetic UI images into {synthetic_dir} ...")
        synth_ui.generate_corpus(synthetic_dir, args.count, args.seed)

    extra_corpora, missing = discover_corpora(
        args.eval_dir, [(name, CorpusKind.BENIGN) for name in EXTRA_BENIGN_CORPORA]
    )
    for name in missing:
        print(f"skipping '{name}': no corpus at {args.eval_dir / name} (not generated by this script)")

    print(f"loading {args.model} ...")
    classifier = model_mod.load_classifier(args.model)
    print(
        f"resolved NSFW class index {classifier.nsfw_index} "
        f"from id2label={dict(classifier.model.config.id2label)}"
    )

    specs = [
        CorpusSpec(name="synthetic-ui", root=synthetic_dir, kind=CorpusKind.BENIGN),
        *extra_corpora,
    ]
    for spec in specs:
        result = eval_mod.evaluate_corpus(spec, lambda p: model_mod.score_path(classifier, p))
        print()
        print(eval_mod.report(result))


if __name__ == "__main__":
    main()
